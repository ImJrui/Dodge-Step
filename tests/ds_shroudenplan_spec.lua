local T = dofile("tests/ds_testutil.lua")
local Plan = require("ds_shroudenplan")
local function radius(p) return math.sqrt(p.x * p.x + p.z * p.z) end

T.test("portal front cone includes 60 degrees and the configured radius", function()
    local b = T.entity("shrouden", 0, 0, "punch_pre")
    local edge = DS_SHROUDEN.FRONT_RADIUS / 2
    local p = T.entity("wortox", edge, -edge * math.sqrt(3))
    T.eq(Plan.GetThreat(b, p), "portal")
    p.x, p.z = edge + 0.01, -(edge + 0.01) * math.sqrt(3)
    T.eq(Plan.GetThreat(b, p), nil)
    p.x, p.z = 0, -10
    T.eq(Plan.GetThreat(b, p), nil)
    p.x, p.z = -4, 0
    T.eq(Plan.GetThreat(b, p), nil)
end)
T.test("rotation uses DST negative z facing convention", function()
    local b = T.entity("shrouden", 0, 0, "punch_loop", 90)
    T.eq(Plan.GetThreat(b, T.entity("wilson", 0, -10)), "portal")
    T.eq(Plan.GetThreat(b, T.entity("wilson", 0, 10)), nil)
end)
T.test("laser ignores height and excludes initial lift-off", function()
    local b = T.entity("shrouden", 0, 0, "optic_blast_pre1", 0, 100)
    local p = T.entity("wilson", DS_SHROUDEN.LASER_RADIUS, 0)
    T.eq(Plan.GetThreat(b, p), nil)
    for _, anim in ipairs({"optic_blast_pre2", "optic_blast_loop", "optic_blast_pre3"}) do
        b.animation = anim
        T.eq(Plan.GetThreat(b, p), "laser")
    end
    p.x = DS_SHROUDEN.LASER_RADIUS + 0.01
    T.eq(Plan.GetThreat(b, p), nil)
end)
T.test("puddle distance includes four and a half and not teleport preparation", function()
    local b = T.entity("shrouden", 0, 0, "teleport_pre")
    local p = T.entity("wilson", 4.5, 0)
    T.eq(Plan.GetThreat(b, p), nil)
    b.animation = "teleport_loop"
    T.eq(Plan.GetThreat(b, p), "puddle")
    p.x = 4.51
    T.eq(Plan.GetThreat(b, p), nil)
end)
T.test("portal picks nearest rear annulus outside radius four", function()
    local b = T.entity("shrouden", 0, 0, "punch_pre")
    local p = T.entity("wilson", 8, 0)
    local point = Plan.FindLanding(b, p, "portal", function() return true end)
    T.near(radius(point), 4.25)
    assert(point.x < 0 and -point.x / radius(point) >= 0.5 - 0.00001)
end)
T.test("portal exhausts rear annulus before farthest-first fallback", function()
    local b = T.entity("shrouden", 0, 0, "punch_loop")
    local p = T.entity("wilson", 8, 0)
    local point = Plan.FindLanding(b, p, "portal", function(pt) return radius(pt) > 9 end)
    T.near(radius(point), 20)
end)
T.test("fallback selects next farthest ring if outer ring blocked", function()
    local b = T.entity("shrouden", 0, 0, "teleport_loop")
    local p = T.entity("wilson", 0, 0)
    local point = Plan.FindLanding(b, p, "puddle", function(pt) return radius(pt) <= 18.5 + 0.00001 end)
    T.near(radius(point), 18.5)
end)
T.test("no valid landing returns nil and never sends fallback outside radius", function()
    local b = T.entity("shrouden", 0, 0, "punch_pre")
    local p = T.entity("wilson", 12, 0)
    local point = Plan.FindLanding(b, p, "portal", function(pt)
        assert(radius(pt) <= 20.00001)
        local dx, dz = pt.x - p.x, pt.z - p.z
        assert(dx * dx + dz * dz <= 36 * 36)
        assert(dx * dx + dz * dz >= 9)
        return false
    end)
    T.eq(point, nil)
end)
T.test("fallback never lands back inside laser or puddle danger", function()
    local b = T.entity("shrouden", 0, 0, "optic_blast_pre2")
    local p = T.entity("wilson", 0, 0)
    T.eq(Plan.FindLanding(b, p, "laser", function(pt) return radius(pt) <= DS_SHROUDEN.LASER_RADIUS end), nil)
    T.eq(Plan.FindLanding(b, p, "puddle", function(pt) return radius(pt) <= 4.5 end), nil)
end)
T.test("portal rectangle fills the near sides up to the sector edges", function()
    local b = T.entity("shrouden", 0, 0, "punch_pre")
    T.eq(Plan.GetThreat(b, T.entity("wilson", 1, 4)), "portal")
    T.eq(Plan.GetThreat(b, T.entity("wilson", 1, -4)), "portal")
    local depth = 4 / math.sqrt(3)
    T.eq(Plan.GetThreat(b, T.entity("wilson", 0, 4)), "portal")
    T.eq(Plan.GetThreat(b, T.entity("wilson", depth, 4)), "portal")
    T.eq(Plan.GetThreat(b, T.entity("wilson", depth, 4.01)), nil)
    T.eq(Plan.GetThreat(b, T.entity("wilson", DS_SHROUDEN.FRONT_RADIUS, 4)), nil)
    T.eq(Plan.GetThreat(b, T.entity("wilson", DS_SHROUDEN.FRONT_RADIUS, -4)), nil)
    T.eq(Plan.GetThreat(b, T.entity("wilson", DS_SHROUDEN.FRONT_RADIUS + 0.01, 4)), nil)
    T.eq(Plan.GetThreat(b, T.entity("wilson", 1, 4.01)), nil)
    T.eq(Plan.GetThreat(b, T.entity("wilson", -0.01, 3)), nil)
end)
T.test("portal sector still includes points outside the rectangle", function()
    local b = T.entity("shrouden", 0, 0, "punch_loop")
    T.eq(Plan.GetThreat(b, T.entity("wilson", 6, -6 * math.sqrt(3))), "portal")
end)
T.test("portal rectangle follows Boss rotation and world position", function()
    local b = T.entity("shrouden", 20, 30, "punch_loop", 90, 100)
    T.eq(Plan.GetThreat(b, T.entity("wilson", 24, 30 - DS_SHROUDEN.FRONT_RADIUS)), nil)
    T.eq(Plan.GetThreat(b, T.entity("wilson", 24, 30 - 4 / math.sqrt(3))), "portal")
    T.eq(Plan.GetThreat(b, T.entity("wilson", 24, 29)), "portal")
    T.eq(Plan.GetThreat(b, T.entity("wilson", 24, 30 - DS_SHROUDEN.FRONT_RADIUS - 0.01)), nil)
    T.eq(Plan.GetThreat(b, T.entity("wilson", 23, 30.01)), nil)
end)
T.test("portal fallback never accepts the added rectangle-only danger", function()
    local b = T.entity("shrouden", 0, 0, "punch_pre")
    local p = T.entity("wilson", 2, 0)
    local point = Plan.FindLanding(b, p, "portal", function(pt)
        return pt.x >= 0 and pt.x <= 4 / math.sqrt(3) and math.abs(pt.z) <= 4
    end)
    T.eq(point, nil)
end)
T.test("portal fallback accepts sampled old rectangle corners outside the sector", function()
    local b = T.entity("shrouden", 0, 0, "punch_pre")
    local p = T.entity("wilson", 8, 0)
    local previous_step = DS_SHROUDEN.ESCAPE_STEP
    DS_SHROUDEN.ESCAPE_STEP = 0.25
    local point = Plan.FindLanding(b, p, "portal", function(pt)
        return pt.x > DS_SHROUDEN.FRONT_RADIUS - 0.5 and pt.x <= DS_SHROUDEN.FRONT_RADIUS
            and math.abs(pt.z) >= 3 and math.abs(pt.z) <= 4
    end)
    DS_SHROUDEN.ESCAPE_STEP = previous_step
    assert(point, "sampled points outside the short rectangle and sector must remain eligible")
    T.eq(Plan.GetThreat(b, T.entity("wilson", point.x, point.z)), nil)
end)
T.summary()
