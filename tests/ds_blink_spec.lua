local T = dofile("tests/ds_blink_testutil.lua")
local function submit(f)
    f:Seed()
    assert(f.blink:Start(f.boss, "portal"))
    return f.blink:Update()
end
T.test("stash take and blink requests are submitted in one update at the same time", function()
    local f = T.fixture()
    local staff, mouse, weapon = T.item("orangestaff"), T.item("twigs"), T.item("spear")
    f.inventory.slots[1], f.inventory.active, f.inventory.equips.hands = staff, mouse, weapon
    submit(f)
    T.eq(#f.calls, 3)
    T.eq(f.calls[1].name, "PutAllOfActiveItemInSlot")
    T.eq(f.calls[2].name, "TakeActiveItemFromAllOfSlot")
    T.eq(f.calls[3].name, "RightClick")
    for _, call in ipairs(f.calls) do T.eq(call.at, 0) end
    T.eq(f.inventory.active, mouse, "raw submission must not falsify the predicted inventory")
    f:Deliver()
    T.eq(#f.executed, 1)
    T.eq(f.executed[1].invobject, staff)
    T.eq(f.serverinventory.equips.hands, staff)
    T.eq(f.serverinventory.active, nil)
end)
